/**
 * Runs before every build (see "prebuild" in package.json).
 *
 * Downloads what editors saved in the live content editor (/editor/) into
 * src/data/cms/{blogs,treatments,doctors,hospitals}.json, plus any images they
 * uploaded into src/assets/cms/, and regenerates src/data/cms/media.ts. The
 * data modules (src/data/*.ts) merge these in, so the static site — every
 * language, menus, search, sitemap — includes the editors' changes.
 *
 * Needs, in the environment or a project-root .env file (not committed):
 *   CMS_EXPORT_KEY   same value as CMS_EXPORT_KEY in the live site's .env
 *   CMS_EXPORT_URL   optional, defaults to the live site's export endpoint
 *
 * Without a key, or if the live site can't be reached, the build continues
 * with the content already in src/data/cms/ (and says so).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const TYPES = ['blogs', 'treatments', 'doctors', 'hospitals'];
const dataDir = join(root, 'src/data/cms');
const assetsDir = join(root, 'src/assets/cms');

function loadDotEnv() {
	const path = join(root, '.env');
	if (!existsSync(path)) return {};
	const env = {};
	for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
		const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
		if (m) env[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
	}
	return env;
}

const dotEnv = loadDotEnv();
const KEY = process.env.CMS_EXPORT_KEY || dotEnv.CMS_EXPORT_KEY || '';
const URL_ = process.env.CMS_EXPORT_URL || dotEnv.CMS_EXPORT_URL || 'https://alispromeditours.com/editor/api/export.php';

mkdirSync(dataDir, { recursive: true });
for (const type of TYPES) {
	const file = join(dataDir, `${type}.json`);
	if (!existsSync(file)) writeFileSync(file, '{}\n');
}

/** Every "/media/{type}/{file}" path mentioned anywhere in the saved records. */
function mediaPaths(value, found = new Set()) {
	if (typeof value === 'string' && /^\/media\/(blogs|treatments|doctors|hospitals)\/[a-f0-9]{20}\.(jpg|png|webp|gif)$/.test(value)) found.add(value);
	else if (Array.isArray(value)) value.forEach((v) => mediaPaths(v, found));
	else if (value && typeof value === 'object') Object.values(value).forEach((v) => mediaPaths(v, found));
	return found;
}

function writeMediaModule(paths) {
	const present = [...paths].filter((p) => existsSync(join(assetsDir, p.replace(/^\/media\//, '')))).sort();
	const imports = present.map((p, i) => `import m${i} from '../../assets/cms/${p.replace(/^\/media\//, '')}';`);
	const entries = present.map((p, i) => `\t'${p}': m${i},`);
	writeFileSync(
		join(dataDir, 'media.ts'),
		[
			'// Generated by scripts/pull-cms-data.mjs — images uploaded in the content',
			'// editor (/editor/), downloaded so the build can optimise them. Do not edit.',
			"import type { ImageMetadata } from 'astro';",
			...imports,
			'',
			`export const cmsMedia: Record<string, ImageMetadata> = {${entries.length ? `\n${entries.join('\n')}\n` : ''}};`,
			'',
		].join('\n'),
	);
	return present.length;
}

async function main() {
	if (!KEY) {
		console.log('[cms] CMS_EXPORT_KEY not set — building with the editor content already in src/data/cms/.');
		return;
	}
	let data;
	try {
		const res = await fetch(URL_, { headers: { 'X-CMS-Key': KEY }, signal: AbortSignal.timeout(30_000) });
		if (!res.ok) throw new Error(`HTTP ${res.status}`);
		data = await res.json();
	} catch (err) {
		console.warn(`[cms] WARNING: could not download editor content from ${URL_} (${err.message}). Building with the content already in src/data/cms/.`);
		return;
	}

	const all = new Set();
	for (const type of TYPES) {
		const records = data?.[type] && typeof data[type] === 'object' ? data[type] : {};
		writeFileSync(join(dataDir, `${type}.json`), JSON.stringify(records, null, '\t') + '\n');
		mediaPaths(records, all);
	}

	const origin = new URL(URL_).origin;
	let downloaded = 0;
	for (const path of all) {
		const dest = join(assetsDir, path.replace(/^\/media\//, ''));
		if (existsSync(dest)) continue;
		try {
			const res = await fetch(origin + path, { signal: AbortSignal.timeout(30_000) });
			if (!res.ok) throw new Error(`HTTP ${res.status}`);
			mkdirSync(dirname(dest), { recursive: true });
			writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
			downloaded++;
		} catch (err) {
			console.warn(`[cms] WARNING: could not download ${path} (${err.message}); that item keeps its previous image.`);
		}
	}
	const images = writeMediaModule(all);
	const counts = TYPES.map((t) => `${Object.keys(data?.[t] ?? {}).length} ${t}`).join(', ');
	console.log(`[cms] pulled editor content: ${counts}; ${images} image(s) (${downloaded} new).`);
}

await main();
